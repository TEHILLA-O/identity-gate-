"""Create a local .env. Secrets stay out of git."""

from __future__ import annotations

import secrets
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
TARGET = ROOT / ".env"
EXAMPLE = """# Local demonstration only. Generated by scripts/init_env.py.
# Do not reuse these values outside this workstation.

POSTGRES_PASSWORD={postgres}
KC_ADMIN_USERNAME=admin
KC_ADMIN_PASSWORD={admin}
IDENTITYGATE_CLIENT_SECRET={identitygate}
FINANCE_CLIENT_SECRET={finance}
PROJECTS_CLIENT_SECRET={projects}
SCIM_CLIENT_SECRET={scim}
DOWNSTREAM_SCIM_TOKEN={downstream}
DEMO_USER_PASSWORD={demo}
SESSION_SECRET={session}
DATABASE_URL=postgresql+psycopg://identitygate:{postgres}@postgres:5432/identitygate
KEYCLOAK_INTERNAL_URL=http://keycloak:8080
KEYCLOAK_PUBLIC_URL=http://localhost:8080
KEYCLOAK_REALM=northstar
OIDC_CLIENT_ID=identitygate
OIDC_CLIENT_SECRET={identitygate}
OIDC_AUDIENCE=identitygate-api
SCIM_CLIENT_ID=identitygate-provisioner
SCIM_CLIENT_SECRET={scim}
SCIM_AUDIENCE=http://localhost:8080/realms/northstar/scim/v2
KC_ADMIN_USERNAME=admin
KC_ADMIN_PASSWORD={admin}
FINANCE_CLIENT_SECRET={finance}
PROJECTS_CLIENT_SECRET={projects}
DOWNSTREAM_SCIM_URL=http://directory:8103/scim/v2
DOWNSTREAM_SCIM_TOKEN={downstream}
PUBLIC_APP_URL=http://localhost:5173
COOKIE_SECURE=false
AUTO_EXPIRE=false
WORKER_ENABLED=true
ENVIRONMENT_NAME=local
"""


def token() -> str:
    return secrets.token_urlsafe(32)


def password() -> str:
    # Length and character mix satisfy the realm password policy.
    return "Ns-" + secrets.token_urlsafe(18)


def main() -> None:
    if TARGET.exists():
        print(f"{TARGET} already exists")
        return
    values = {
        "postgres": token(),
        "admin": password(),
        "identitygate": token(),
        "finance": token(),
        "projects": token(),
        "scim": token(),
        "downstream": token(),
        "demo": password(),
        "session": token(),
    }
    TARGET.write_text(EXAMPLE.format(**values), encoding="utf-8")
    print("Wrote .env")
    print("Local demonstration password (also DEMO_USER_PASSWORD in .env):")
    print(values["demo"])
    print("Keycloak admin password:")
    print(values["admin"])


if __name__ == "__main__":
    main()
